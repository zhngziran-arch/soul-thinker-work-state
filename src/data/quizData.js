export function dimensionScores(answers) {
  return dimensions.map(dim => {
    const rows = questions.filter(item => item.dimension === dim.id)
    const answered = rows.filter(item => item.options.some(option => option.id === answers[item.id]))
    const score = answered.length === rows.length
      ? Math.round(answered.reduce((sum, item) => sum + item.options.find(option => option.id === answers[item.id]).score, 0) / (rows.length * 3) * 100)
      : null
    return { ...dim, score }
  })
}

export function activeFollowup(answers) {
  if (questions.some(item => !item.options.some(option => option.id === answers[item.id]))) return null
  const scores = dimensionScores(answers)
  const hasAlert = questions.some(item => item.options.find(option => option.id === answers[item.id])?.alert)
  if (!hasAlert && scores.every(dim => dim.score >= 75)) return positiveFollowup
  return followups[[...scores].sort((a, b) => a.score - b.score)[0].id]
}

export function quizSteps(answers) {
  const followup = activeFollowup(answers)
  return followup ? [...questions, followup, priorityQuestion] : questions
}
